"""Small adapter for the repository's fixed SQL statements, not a general SQL translator.

PostgreSQL writes currently share a database-wide advisory transaction lock. This
preserves the reference engine's serial writer semantics; it is a correctness
baseline, not a horizontally scalable locking strategy.
"""
import re
import sqlite3


class Record(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def record_factory(cursor):
    names = [c.name for c in (cursor.description or [])]
    return lambda values: Record(zip(names, values))


class Postgres:
    dialect = 'postgres'

    def __init__(self, dsn):
        import psycopg
        self.raw = psycopg.connect(dsn, autocommit=True, row_factory=record_factory,
                                   connect_timeout=5)
        self.transaction = None

    def __enter__(self):
        if self.transaction is not None:
            raise RuntimeError('nested database contexts are not supported')
        self.transaction = self.raw.transaction()
        self.transaction.__enter__()
        self.raw.execute('SELECT pg_advisory_xact_lock(782347112)')
        return self

    def __exit__(self, *args):
        tx, self.transaction = self.transaction, None
        return tx.__exit__(*args)

    def execute(self, sql, params=()):
        if sql.strip().upper() == 'BEGIN IMMEDIATE':
            if self.transaction is None:
                raise RuntimeError('transaction context required')
            return self.raw.execute('SELECT 1')
        # These are the only dialect differences in the fixed repository schema.
        sql = sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT',
                          'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql)
        for table in ('replies', 'response_segments', 'transcript_outbox'):
            if re.match(r'\s*CREATE TABLE IF NOT EXISTS ' + table + r'\s*\(', sql):
                end = sql.rfind(')')
                sql = sql[:end] + ', _ordinal BIGINT GENERATED ALWAYS AS IDENTITY' + sql[end:]
        sql = re.sub(r'\browid\b', '_ordinal', sql)
        return self.raw.execute(sql.replace('?', '%s'), tuple(int(p) if isinstance(p, bool) else p for p in params))

    def executescript(self, script):
        with self:
            for statement in script.split(';'):
                if statement.strip():
                    self.execute(statement)

    def commit(self):
        self.raw.commit()

    def close(self):
        self.raw.close()


def connect(path, check_same_thread=True):
    if str(path).startswith(('postgresql://', 'postgres://')):
        return Postgres(path)
    db = sqlite3.connect(path, check_same_thread=check_same_thread)
    db.row_factory = sqlite3.Row
    db.execute('PRAGMA foreign_keys=ON')
    return db


def table_exists(db, name):
    if isinstance(db, Postgres):
        return bool(db.execute('SELECT 1 FROM information_schema.tables WHERE table_schema=current_schema() AND table_name=?', (name,)).fetchone())
    return bool(db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone())


def columns(db, table):
    if isinstance(db, Postgres):
        return {r[0] for r in db.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?', (table,)).fetchall()}
    # Internal schema names only; no caller input is interpolated.
    if table != 'stage_calls':
        raise ValueError('unsupported schema inspection')
    return {r['name'] for r in db.execute('PRAGMA table_info(stage_calls)')}
